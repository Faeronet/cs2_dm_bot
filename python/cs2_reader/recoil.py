_pattern_cache: dict[str, tuple[tuple[float, float], ...]] = {}


def _weapon_key(item_id: int = 0, name: str = "") -> str:
    item_id, n = resolve_weapon(item_id if item_id else name)
    n = n or name
    return _ALIAS.get(n, n)


def _build_pattern(keys: list[tuple[int, float, float]], n: int) -> tuple[tuple[float, float], ...]:
    keys = sorted(keys)
    out: list[tuple[float, float]] = []
    for i in range(n + 1):
        if i <= keys[0][0]:
            out.append((keys[0][1], keys[0][2]))
            continue
        if i >= keys[-1][0]:
            y, p = keys[-1][1], keys[-1][2]
            extra = i - keys[-1][0]
            out.append((y * (0.97 ** extra), p + 0.03 * extra))
            continue
        lo = keys[0]
        hi = keys[-1]
        for a, b in zip(keys, keys[1:]):
            if a[0] <= i <= b[0]:
                lo, hi = a, b
                break
        span = max(1, hi[0] - lo[0])
        t = (i - lo[0]) / span
        t = t * t * (3.0 - 2.0 * t)
        out.append((lo[1] + (hi[1] - lo[1]) * t, lo[2] + (hi[2] - lo[2]) * t))
    return tuple(out)


def recoil_pattern(item_id: int = 0, name: str = "") -> tuple[tuple[float, float], ...]:
    key = _weapon_key(item_id, name)
    if key in _pattern_cache:
        return _pattern_cache[key]
    item_id, _ = resolve_weapon(item_id if item_id else name)
    n = WEAPON_CLIP.get(item_id, 30)
    keys = _KEYS.get(key)
    if keys is None:
        pat = tuple((0.0, 0.0) for _ in range(n + 1))
    else:
        pat = _build_pattern(keys, n)
    _pattern_cache[key] = pat
    return pat


def recoil_offset(item_id: int, name: str, shots: int, frac: float = 0.0) -> tuple[float, float]:
    """Кумулятивная компенсация после `shots` пуль; frac ∈ [0,1] — доля пути к следующей."""
    pat = recoil_pattern(item_id, name)
    if not pat:
        return 0.0, 0.0
    i = max(0, min(int(shots), len(pat) - 1))
    y0, p0 = pat[i]
    if i + 1 >= len(pat) or frac <= 0.0:
        return y0, p0
    t = max(0.0, min(1.0, frac))
    y1, p1 = pat[i + 1]
    return y0 + (y1 - y0) * t, p0 + (p1 - p0) * t


def tap_cycle_s(item_id: int = 0, name: str = "") -> float:
    item_id, _ = resolve_weapon(item_id if item_id else name)
    if item_id in _TAP_CYCLE:
        return _TAP_CYCLE[item_id]
    if weapon_is_auto(item_id, name):
        return weapon_cycle_s(item_id, name)
    rpm = weapon_rpm(item_id, name)
    return 60.0 / rpm if rpm > 1.0 else 0.20


def tap_gap_range(item_id: int = 0, name: str = "") -> tuple[float, float]:
    """Интервал ожидания между тапами (сброс отдачи / затвор)."""
    item_id, _ = resolve_weapon(item_id if item_id else name)
    cycle = tap_cycle_s(item_id, name)
    lo, hi = _TAP_GAP.get(item_id, (cycle + 0.06, cycle + 0.22))
    lo = max(cycle, lo)
    hi = max(lo + 0.03, hi)
    return lo, hi


def spray_recover_s(item_id: int = 0, name: str = "") -> float:
    """Через столько с после отпускания ЛКМ спрей в CS2 почти сбрасывается."""
    rpm = weapon_rpm(item_id, name)
    if rpm >= 500:
        return 0.37
    if rpm >= 200:
        return 0.42
    return 0.50
